"""Places the Kokoro voiceover sections on the timeline and writes timing.js.
Reads build/sec_<k>.wav + build/sec_words.json (tools/tts.py). Sections run back to back with short beats,
plus extra room after the visual proof shots. Versions: ig (Comment PROMPTS), yt (pinned comment).
Usage: python3 vo.py"""
import json, numpy as np, soundfile as sf
from scipy.signal import resample_poly
SR = 48000
D = json.load(open('build/sec_words.json'))
LEAD, GAP, HOLD = 0.15, 0.35, 2.4
PAD = {'s4': 0.25, 's5': 0.7, 's6': 0.6, 's7': 0.7, 's8': 0.2}   # room for the effect to land after the line
SPLIT = {'s5': (5, 0.75)}   # extra beat before word 5 ("Particle") so KINETIC TYPE can be read
ORDER = {'ig': ['s1', 's2', 's3', 's4', 's5', 's6', 's7', 's8', 's9ig'], 'yt': ['s1', 's2', 's3', 's4', 's5', 's6', 's7', 's8', 's9yt']}
T = {}
for v, order in ORDER.items():
    t, secs, clips = LEAD, {}, []
    for k in order:
        a, sr = sf.read(f'build/sec_{k}.wav'); a = resample_poly(a, SR, sr)
        name, ws, dur = k[:2], D[k]['words'], D[k]['dur']
        j, extra = SPLIT.get(k, (len(ws), 0))
        cut = (ws[j - 1]['e'] + ws[j]['s']) / 2 if extra else dur
        shift = lambda x: x + (extra if x >= cut else 0)
        secs[name] = {'t': round(t, 3), 'e': round(t + dur + extra, 3),
                      'w': [{'w': w['w'], 't': round(t + shift(w['s']), 3), 'e': round(t + shift(w['e']), 3)} for w in ws]}
        clips.append((t, a[:int(cut * SR)]))
        if extra: clips.append((t + cut + extra, a[int(cut * SR):]))
        t += dur + extra + GAP + PAD.get(k, 0)
    total = round(secs['s9']['e'] + HOLD, 2)
    buf = np.zeros(int(total * SR))
    for t0, a in clips: i = int(t0 * SR); buf[i:i + len(a)] += a[:len(buf) - i]
    buf = buf / np.abs(buf).max() * 10 ** (-1.5 / 20)
    sf.write(f'build/vo_{v}.wav', np.stack([buf, buf], 1), SR, subtype='PCM_16')
    shots = [0] + [round(secs[f's{n}']['t'] - 0.18, 3) for n in range(2, 10)] + [total]
    T[v] = {'total': total, 'shots': shots, 'secs': secs}
    print(v, 'total', total, 'shots', shots)
open('timing.js', 'w').write('/* generated by vo.py */\nconst TIMING = ' + json.dumps(T) + ';\n')
