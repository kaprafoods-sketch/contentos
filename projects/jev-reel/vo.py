"""Places the voiceover on the reel timeline and writes timing.js.
Reads build/vo_a.mp3 (ElevenLabs take, both endings) and build/vo_a_words.json (faster-whisper words).
Pauses longer than CAP are shortened so the reel lands near 60 s; the line before each list number keeps a beat.
Writes build/vo_ig.wav, build/vo_yt.wav and timing.js (absolute word times for both versions).
Usage: python3 vo.py"""
import json, subprocess, numpy as np
from scipy.io import wavfile

SR = 48000
CAP = 0.32          # longest pause kept inside the read
BEAT = 0.45         # pause kept before "Four ways", "One", "Two", "Three", "Four", "Claude does"
LEAD = 0.25         # silence before the first word
TAIL = 0.35         # time after the last word before the hard cut to black
TEMPO = 1.04        # whole read slightly quicker so the reel lands at 60 s
BEAT_AT = {55, 60, 80, 104, 121, 131}
IG = list(range(0, 158))                    # ... Comment Jev and I'll DM you the links.
YT = list(range(0, 150)) + list(range(158, 164))  # ... Links are in the pinned comment.

words = json.load(open('build/vo_a_words.json'))
raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', 'build/vo_a.mp3', '-f', 's16le', '-ac', '1', '-ar', str(SR), '-'],
                     capture_output=True, check=True).stdout
src = np.frombuffer(raw, np.int16).astype(np.float64) / 32768

def build(idx, name):
    # group consecutive words into phrases split at pauses > 0.12 s or at a jump in index
    phrases, cur = [], [idx[0]]
    for a, b in zip(idx, idx[1:]):
        if b != a + 1 or words[b]['s'] - words[a]['e'] > 0.12: phrases.append(cur); cur = [b]
        else: cur.append(b)
    phrases.append(cur)
    out, t, abs_w = [], LEAD, []
    for k, ph in enumerate(phrases):
        s0 = max(0, words[ph[0]]['s'] - 0.04); s1 = words[ph[-1]]['e'] + 0.06
        if k + 1 < len(phrases) and phrases[k + 1][0] == ph[-1] + 1: s1 = min(s1, words[ph[-1] + 1]['s'] - 0.02)
        seg = src[int(s0 * SR):int(s1 * SR)].copy()
        f = int(0.012 * SR); seg[:f] *= np.linspace(0, 1, f); seg[-f:] *= np.linspace(1, 0, f)
        if k:
            prev = phrases[k - 1][-1]
            gap = words[ph[0]]['s'] - words[prev]['e'] if ph[0] == prev + 1 else 0.5
            t += max(BEAT, min(gap, 0.6)) if ph[0] in BEAT_AT else min(gap, CAP)
        out.append((t, seg))
        for i in ph: abs_w.append({'i': i, 'w': words[i]['w'], 't': round(t + words[i]['s'] - s0, 3), 'e': round(t + words[i]['e'] - s0, 3)})
        t += len(seg) / SR
    buf = np.zeros(int(t * SR) + SR)
    for t0, seg in out: buf[int(t0 * SR):int(t0 * SR) + len(seg)] += seg
    r = subprocess.run(['ffmpeg', '-v', 'error', '-f', 'f64le', '-ar', str(SR), '-ac', '1', '-i', '-', '-af', f'atempo={TEMPO}',
                        '-f', 'f64le', '-'], input=buf.tobytes(), capture_output=True, check=True).stdout
    buf = np.frombuffer(r, np.float64).copy()
    for w in abs_w: w['t'] = round(w['t'] / TEMPO, 3); w['e'] = round(w['e'] / TEMPO, 3)
    total = round(abs_w[-1]['e'] + TAIL, 2)
    buf = np.pad(buf, (0, max(0, int(total * SR) - len(buf))))[:int(total * SR)]
    buf = buf / np.abs(buf).max() * 10 ** (-1.5 / 20)
    wavfile.write(f'build/vo_{name}.wav', SR, (np.stack([buf, buf], 1) * 32767).astype(np.int16))
    print(name, 'total', total, 's')
    return {'total': total, 'words': abs_w}

T = {'ig': build(IG, 'ig'), 'yt': build(YT, 'yt')}
open('timing.js', 'w').write('/* generated by vo.py */\nconst TIMING = ' + json.dumps(T) + ';\n')
