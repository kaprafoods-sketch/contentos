"""Places the VO take on the 42 s timeline and writes timing.js.
Reads build/vo_a.mp3 (ElevenLabs take with every line, both endings and the alternate proof line) and build/vo_a_words.json.
Each spoken section starts at its shot time from the brief; inside a section the natural read is kept.
Versions: ig (fallback proof line, Instagram CTA), yt (fallback proof line, pinned comment CTA),
          ig220 (the 220x proof line; only for use once the figure is confirmed). Usage: python3 vo.py"""
import json, subprocess, numpy as np
from scipy.io import wavfile

SR = 48000
TOTAL = 42.0
words = json.load(open('build/vo_a_words.json'))
raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', 'build/vo_a.mp3', '-f', 's16le', '-ac', '1', '-ar', str(SR), '-'],
                     capture_output=True, check=True).stdout
src = np.frombuffer(raw, np.int16).astype(np.float64) / 32768
R = lambda a, b: list(range(a, b + 1))
S1, S2, S3, S4 = R(0, 1), R(2, 12), R(13, 32), R(33, 47)
FALLBACK, CLAIM = R(48, 56), R(48, 51) + R(68, 74)
CTA_IG, CTA_YT = R(57, 67), R(75, 83)
# section start times (first word onset), from the brief's shot times plus a short lead in
STARTS = [0.12, 3.25, 9.15, 17.2, 26.25, 34.35]
VERSIONS = {'ig': [S1, S2, S3, S4, FALLBACK, CTA_IG], 'yt': [S1, S2, S3, S4, FALLBACK, CTA_YT],
            'ig220': [S1, S2, S3, S4, CLAIM, CTA_IG]}

def runs(idx):
    out, cur = [], [idx[0]]
    for a, b in zip(idx, idx[1:]):
        if b == a + 1: cur.append(b)
        else: out.append(cur); cur = [b]
    return out + [cur]

def build(name, sections):
    buf = np.zeros(int(TOTAL * SR)); abs_w = []
    for t_sec, sec in zip(STARTS, sections):
        t = t_sec
        for k, ph in enumerate(runs(sec)):
            s0 = max(0, words[ph[0]]['s'] - 0.05); s1 = words[ph[-1]]['e'] + 0.08
            if ph[-1] + 1 < len(words): s1 = min(s1, words[ph[-1] + 1]['s'] - 0.02)
            seg = src[int(s0 * SR):int(s1 * SR)].copy()
            f = int(0.01 * SR); seg[:f] *= np.linspace(0, 1, f); seg[-f:] *= np.linspace(1, 0, f)
            if k: t += 0.32
            off = t - (words[ph[0]]['s'] - s0)      # so the first word onset lands on t
            i0 = int(max(0, off) * SR); buf[i0:i0 + len(seg)] += seg[:len(buf) - i0]
            for i in ph: abs_w.append({'i': i, 'w': words[i]['w'], 't': round(off + words[i]['s'] - s0, 3), 'e': round(off + words[i]['e'] - s0, 3)})
            t = off + len(seg) / SR
    buf = buf / np.abs(buf).max() * 10 ** (-1.5 / 20)
    wavfile.write(f'build/vo_{name}.wav', SR, (np.stack([buf, buf], 1) * 32767).astype(np.int16))
    print(name, 'last word ends', abs_w[-1]['e'])
    return {'total': TOTAL, 'words': abs_w}

T = {k: build(k, v) for k, v in VERSIONS.items()}
open('timing.js', 'w').write('/* generated by vo.py */\nconst TIMING = ' + json.dumps(T) + ';\n')
for w in T['ig']['words']: print(w['i'], w['w'], w['t'], w['e'])
